export interface SpellDefinition {
  id: string
  name: string
  level: number
  school: string
  castingTime: string
  rangeFeet: number | null
  rangeText?: string
  components: string
  duration: string
  concentration: boolean
  target: string
  save: string | null
  attack: boolean
  effect: string
  higherLevels: string
  /** Пустой массив: заклинание не в списке класса, только домен или иной источник */
  classIds: string[]
}

function spell(
  p: Omit<SpellDefinition, 'higherLevels' | 'classIds'> & {
    higherLevels?: string
    classIds?: string[]
  },
): SpellDefinition {
  return { higherLevels: '', classIds: ['cleric'], ...p }
}

