export function getSpell(id: string): SpellDefinition | undefined {
  return SPELLS.find((s) => s.id === id)
}

export function getSpellsByIds(ids: string[]): SpellDefinition[] {
  return ids.map((id) => getSpell(id)).filter((s): s is SpellDefinition => !!s)
}

export function getClassSpells(classId: string): SpellDefinition[] {
  return SPELLS.filter((s) => s.classIds.includes(classId))
}

export function getClassCantrips(classId: string): SpellDefinition[] {
  return getClassSpells(classId).filter((s) => s.level === 0)
}

export function getPreparableClassSpells(classId: string, maxSlotLevel: number): SpellDefinition[] {
  return getClassSpells(classId).filter((s) => s.level >= 1 && s.level <= maxSlotLevel)
}

export function groupSpellsByLevel(spells: SpellDefinition[]): { level: number; spells: SpellDefinition[] }[] {
  const levels = [...new Set(spells.map((s) => s.level))].sort((a, b) => a - b)
  return levels.map((level) => ({
    level,
    spells: spells.filter((s) => s.level === level).sort((a, b) => a.name.localeCompare(b.name, 'ru')),
  }))
}
